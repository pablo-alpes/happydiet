#!/usr/bin/env bash
# HappyDiet — Full production setup (APIs, Firestore DBs, .env, auth)
# Run from repo root: ./scripts/setup-production.sh [PROJECT_ID]
# Or: ./scripts/setup-production.sh (uses gcloud config project)

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
PROJECT_ID="${1:-$(gcloud config get-value project 2>/dev/null)}"
REGION="${REGION:-us-central1}"
MEALS_DB="${FIRESTORE_DATABASE_MEALS:-happydiet}"
RULES_DB="${FIRESTORE_DATABASE_RULES:-rules}"

if [[ -z "$PROJECT_ID" ]]; then
  echo "Usage: $0 PROJECT_ID"
  echo "  Or set project: gcloud config set project YOUR_PROJECT_ID"
  exit 1
fi

echo "=== HappyDiet Production Setup ==="
echo "Project:    $PROJECT_ID"
echo "Region:     $REGION"
echo "Meals DB:   $MEALS_DB"
echo "Rules DB:   $RULES_DB"
echo ""

# 1. Set project
gcloud config set project "$PROJECT_ID"

# 2. Enable APIs (Vertex AI, Firestore, TTS, Cloud Run, Build, Artifact Registry)
echo "Enabling APIs..."
gcloud services enable \
  aiplatform.googleapis.com \
  firestore.googleapis.com \
  texttospeech.googleapis.com \
  run.googleapis.com \
  cloudbuild.googleapis.com \
  artifactregistry.googleapis.com \
  --quiet

# 3. Auth (skip if already authenticated; run manually if needed: gcloud auth application-default login)
echo ""
echo "Checking auth..."
if ! gcloud auth application-default print-access-token &>/dev/null; then
  echo "Authenticating (opens browser)..."
  gcloud auth application-default login
fi

# 4. Firestore databases
echo ""
echo "Creating Firestore databases (if not exist)..."

# List existing databases
EXISTING=$(gcloud firestore databases list --format='value(name)' 2>/dev/null || true)

# Ensure (default) exists first — required before creating additional DBs
if ! echo "$EXISTING" | grep -qF 'databases/(default)' 2>/dev/null; then
  echo "  Creating (default) database..."
  gcloud firestore databases create --location="$REGION" --type=firestore-native --quiet 2>/dev/null || {
    echo "  Note: Create Firestore manually: https://console.cloud.google.com/firestore → Create database (Native, $REGION)"
    EXISTING=""  # Will skip additional DBs if default failed
  fi
  EXISTING=$(gcloud firestore databases list --format='value(name)' 2>/dev/null || true)
fi

create_db_if_missing() {
  local db_id="$1"
  if echo "$EXISTING" | grep -q "^projects/$PROJECT_ID/databases/$db_id$" 2>/dev/null; then
    echo "  Database '$db_id' already exists."
  else
    echo "  Creating database '$db_id'..."
    if gcloud firestore databases create --database="$db_id" --location="$REGION" --type=firestore-native --quiet 2>/dev/null; then
      EXISTING="$EXISTING"$'\n'"projects/$PROJECT_ID/databases/$db_id"
    else
      echo "  Note: Create '$db_id' manually in Console: https://console.cloud.google.com/firestore"
    fi
  fi
}

# Create happydiet and rules if we want separate DBs
if [[ "$MEALS_DB" != "(default)" ]]; then
  create_db_if_missing "$MEALS_DB"
fi
if [[ "$RULES_DB" != "(default)" && "$RULES_DB" != "$MEALS_DB" ]]; then
  create_db_if_missing "$RULES_DB"
fi

# 5. Generate .env for backend
ENV_FILE="$REPO_ROOT/backend/.env"
echo ""
echo "Writing backend/.env..."
cat > "$ENV_FILE" << EOF
# HappyDiet Backend — Production config (generated by setup-production.sh)
GOOGLE_CLOUD_PROJECT=$PROJECT_ID
GOOGLE_CLOUD_LOCATION=$REGION
FIRESTORE_DATABASE_MEALS=$MEALS_DB
FIRESTORE_DATABASE_RULES=$RULES_DB

# Optional: API key for X-API-Key (generate: openssl rand -hex 32)
# API_KEY=

# Optional: Vertex AI model (default: gemini-2.5-flash)
# VERTEX_AI_MODEL=gemini-2.5-flash
EOF

echo "  Created $ENV_FILE"

# 6. Generate API key suggestion
API_KEY=$(openssl rand -hex 32 2>/dev/null || echo "CHANGE_ME")
echo ""
echo "=== Next steps ==="
echo "1. (Optional) Add API_KEY to backend/.env: $API_KEY"
echo "2. Deploy backend: ./scripts/deploy.sh"
echo "3. Update iOS HappyDietConfig.plist: BACKEND_URL = https://YOUR-CLOUD-RUN-URL.run.app"
echo "4. Run backend locally: cd backend && npm run dev"
echo ""
echo "Setup complete."
